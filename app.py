conn = st.connection("supabase", type="sql")

def init_db():
    """自動初始化 Supabase 資料表（如未建立）"""
    with conn.session as s:
        s.execute(text("""
            CREATE TABLE IF NOT EXISTS config (
                key TEXT PRIMARY KEY,
                value JSONB
            );
        """))
        s.execute(text("""
            CREATE TABLE IF NOT EXISTS daily_deltas (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
                date_str TEXT NOT NULL,
                major TEXT NOT NULL,
                target_col TEXT NOT NULL,
                val NUMERIC(10, 2) NOT NULL
            );
        """))
        s.commit()

def load_data_from_supabase():
    """從 Supabase 實時讀取人員配置與增量流水 (ttl=0 禁用快取)"""
    try:
        df_raw = conn.query("SELECT value FROM config WHERE key = 'raw_persons';", ttl=0)
        raw_persons = df_raw.iloc[0]['value'] if not df_raw.empty else None

        df_animals = conn.query("SELECT value FROM config WHERE key = 'person_animals';", ttl=0)
        person_animals = df_animals.iloc[0]['value'] if not df_animals.empty else None

        df_deltas = conn.query("SELECT date_str, major, target_col, val FROM daily_deltas ORDER BY id ASC;", ttl=0)
        
        daily_deltas = {}
        if not df_deltas.empty:
            for _, row in df_deltas.iterrows():
                d = row['date_str']
                m = row['major']
                col = row['target_col']
                # 使用 Decimal 精确读取，避免 0.5 在浮点计算中出现异常
                v = float(Decimal(str(row['val'])).quantize(Decimal('0.1'), rounding=ROUND_HALF_UP))
                daily_deltas.setdefault(d, []).append((m, col, v))

        return raw_persons, person_animals, daily_deltas
    except Exception as e:
        st.error(f"資料庫讀取失敗: {e}")
        return None, None, {}

def save_config_to_supabase(raw_persons, person_animals):
    """保存人員及動物對照表配置至 Supabase"""
    with conn.session as s:
        s.execute(text("INSERT INTO config (key, value) VALUES ('raw_persons', :v) ON CONFLICT (key) DO UPDATE SET value = :v;"),
                  {"v": json.dumps(raw_persons, ensure_ascii=False)})
        s.execute(text("INSERT INTO config (key, value) VALUES ('person_animals', :v) ON CONFLICT (key) DO UPDATE SET value = :v;"),
                  {"v": json.dumps(person_animals, ensure_ascii=False)})
        s.commit()

def insert_delta_to_supabase(date_str, major, target_col, val):
    """实时新增一条流水记录；人数按 0.5 人为最小单位精确保存。"""
    exact_val = Decimal(str(val)).quantize(Decimal('0.1'), rounding=ROUND_HALF_UP)
    with conn.session as s:
        s.execute(
            text("INSERT INTO daily_deltas (date_str, major, target_col, val) VALUES (:d, :m, :c, :v);"),
            {"d": date_str, "m": major, "c": target_col, "v": exact_val}
        )
        s.commit()

def delete_delta_from_supabase(date_str, major, target_col, val):
    """實時刪除一條流水紀錄"""
    with conn.session as s:
        s.execute(text("""
            DELETE FROM daily_deltas 
            WHERE id IN (
                SELECT id FROM daily_deltas 
                WHERE date_str = :d AND major = :m AND target_col = :c AND val = :v 
                LIMIT 1
            );
        """), {"d": date_str, "m": major, "c": target_col, "v": float(val)})
        s.commit()

