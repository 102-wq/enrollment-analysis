def fmt_num(v):
    """统一数字显示，确保 0.5 等小数不会在表格中被显示为整数。"""
    if v == "" or v is None:
        return ""
    try:
        val = float(v)

        # 消除浮点计算产生的极小误差，例如 0.49999999999999994
        val = round(val, 1)

        # 避免显示 -0.0
        if abs(val) < 0.000001:
            val = 0.0

        # 整数仍显示整数，小数保留1位
        if val.is_integer():
            return str(int(val))
        return f"{val:.1f}"
    except (ValueError, TypeError):
        return str(v)

